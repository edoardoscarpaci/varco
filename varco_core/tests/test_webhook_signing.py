class TestStandardWebhooksKnownAnswerVector:
    """Known-answer vector from the Standard Webhooks / Svix reference docs."""

    MSG_ID = "msg_p5jXN8AQM9LWM0D4loKWxJek"
    TIMESTAMP = "1614265330"
    PAYLOAD = '{"test": 2432232314}'
    SECRET = "whsec_MfKQ9r8GKYqrTwjUPD8ILPZIo2LaLaSw"
    EXPECTED_SIGNATURE = "v1,g0hM9SsE+OTPJTGt/tmIKtSyZlE3uFJELVlNIOLJ1OE="

    def test_sign_produces_the_spec_vector_signature(self) -> None:
        from varco_core.webhook.signing import StandardWebhooksSigner

        signer = StandardWebhooksSigner(secrets=[self.SECRET])
        headers = signer.sign(
            msg_id=self.MSG_ID,
            timestamp=self.TIMESTAMP,
            payload=self.PAYLOAD,
        )
        assert self.EXPECTED_SIGNATURE in headers["webhook-signature"]

    def test_sign_emits_standard_webhooks_headers(self) -> None:
        from varco_core.webhook.signing import StandardWebhooksSigner

        signer = StandardWebhooksSigner(secrets=[self.SECRET])
        headers = signer.sign(
            msg_id=self.MSG_ID,
            timestamp=self.TIMESTAMP,
            payload=self.PAYLOAD,
        )
        assert headers["webhook-id"] == self.MSG_ID
        assert headers["webhook-timestamp"] == self.TIMESTAMP
        assert "webhook-signature" in headers

    def test_verify_accepts_the_spec_vector(self, monkeypatch) -> None:
        from varco_core.webhook import signing
        from varco_core.webhook.signing import StandardWebhooksSigner

        # The KAT vector's timestamp is a fixed historical instant published
        # by the Standard Webhooks reference docs (2021-02-25) — it will
        # keep aging relative to a real wall clock forever. Freeze
        # `time.time()` to that instant so the tolerance-window check
        # (§D-D4-signing) evaluates the vector on its own terms rather than
        # against however much time has passed since it was recorded.
        monkeypatch.setattr(signing.time, "time", lambda: float(self.TIMESTAMP))

        signer = StandardWebhooksSigner(secrets=[self.SECRET])
        headers = {
            "webhook-id": self.MSG_ID,
            "webhook-timestamp": self.TIMESTAMP,
            "webhook-signature": self.EXPECTED_SIGNATURE,
        }
        assert signer.verify(payload=self.PAYLOAD, headers=headers) is True


