class TestConstantTimeComparison:
    def test_verify_helper_uses_constant_time_compare(self, monkeypatch) -> None:
        # Guards against a naive `==` comparison reintroducing a timing
        # side-channel — the verify path must route through hmac.compare_digest
        # (or equivalent) rather than string equality.
        import hmac as hmac_module

        from varco_core.webhook import signing
        from varco_core.webhook.signing import StandardWebhooksSigner

        # Fixed timestamp, same freeze rationale as the KAT vector test above.
        monkeypatch.setattr(signing.time, "time", lambda: 1700000000.0)

        calls = {"count": 0}
        original = hmac_module.compare_digest

        def _spy(*args, **kwargs):
            calls["count"] += 1
            return original(*args, **kwargs)

        monkeypatch.setattr(hmac_module, "compare_digest", _spy)

        signer = StandardWebhooksSigner(secrets=["whsec_abc"])
        headers = signer.sign(msg_id="msg_x", timestamp="1700000000", payload="{}")
        signer.verify(payload="{}", headers=headers)

        assert calls["count"] >= 1


